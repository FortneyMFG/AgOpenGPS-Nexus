using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;

namespace Aog.Core.Coverage;

/// <summary>
/// Compares legacy V6 coverage CSV exports against Nexus analytics outputs.
/// </summary>
public sealed class CoverageAnalyticsParityHarness
{
    private readonly double _tolerance;

    /// <summary>
    /// Initializes a new instance of the <see cref="CoverageAnalyticsParityHarness"/> class.
    /// </summary>
    /// <param name="tolerance">Absolute tolerance applied when comparing metrics.</param>
    public CoverageAnalyticsParityHarness(double tolerance)
    {
        if (tolerance < 0)
        {
            throw new ArgumentOutOfRangeException(nameof(tolerance));
        }

        _tolerance = tolerance;
    }

    /// <summary>
    /// Loads the supplied CSV files and computes the per-metric deltas.
    /// </summary>
    public CoverageParityReport Compare(string legacyCsvPath, string nexusCsvPath)
    {
        if (legacyCsvPath is null)
        {
            throw new ArgumentNullException(nameof(legacyCsvPath));
        }

        if (nexusCsvPath is null)
        {
            throw new ArgumentNullException(nameof(nexusCsvPath));
        }

        var legacyMetrics = LoadMetrics(legacyCsvPath);
        var nexusMetrics = LoadMetrics(nexusCsvPath);

        if (!legacyMetrics.Keys.SetEquals(nexusMetrics.Keys))
        {
            var missingLegacy = string.Join(", ", legacyMetrics.Keys.Except(nexusMetrics.Keys));
            var missingNexus = string.Join(", ", nexusMetrics.Keys.Except(legacyMetrics.Keys));
            throw new InvalidDataException($"Metric mismatch. Legacy missing [{missingNexus}], Nexus missing [{missingLegacy}].");
        }

        var differences = new List<CoverageMetricDifference>(legacyMetrics.Count);
        foreach (var metric in legacyMetrics.Keys.OrderBy(x => x, StringComparer.OrdinalIgnoreCase))
        {
            var legacyValue = legacyMetrics[metric];
            var nexusValue = nexusMetrics[metric];
            var difference = Math.Abs(legacyValue - nexusValue);
            var withinTolerance = difference <= _tolerance;
            differences.Add(new CoverageMetricDifference(metric, legacyValue, nexusValue, difference, withinTolerance));
        }

        return new CoverageParityReport(differences);
    }

    private static Dictionary<string, double> LoadMetrics(string path)
    {
        if (!File.Exists(path))
        {
            throw new FileNotFoundException("CSV file not found.", path);
        }

        var lines = File.ReadAllLines(path);
        var metrics = new Dictionary<string, double>(StringComparer.OrdinalIgnoreCase);

        foreach (var line in lines)
        {
            if (string.IsNullOrWhiteSpace(line) || line.StartsWith("#", StringComparison.Ordinal))
            {
                continue;
            }

            var parts = line.Split(',', StringSplitOptions.TrimEntries);
            if (parts.Length != 2)
            {
                throw new InvalidDataException($"Unexpected column count in row '{line}'.");
            }

            var metric = parts[0];
            var value = double.Parse(parts[1], CultureInfo.InvariantCulture);
            metrics[metric] = value;
        }

        return metrics;
    }
}

/// <summary>
/// Represents the parity report generated by <see cref="CoverageAnalyticsParityHarness"/>.
/// </summary>
public sealed class CoverageParityReport
{
    public CoverageParityReport(IReadOnlyList<CoverageMetricDifference> metrics)
    {
        Metrics = metrics ?? throw new ArgumentNullException(nameof(metrics));
    }

    /// <summary>
    /// Gets the per-metric differences.
    /// </summary>
    public IReadOnlyList<CoverageMetricDifference> Metrics { get; }

    /// <summary>
    /// Gets a value indicating whether all metrics are within tolerance.
    /// </summary>
    public bool IsWithinTolerance => Metrics.All(m => m.IsWithinTolerance);
}

/// <summary>
/// Captures the difference between legacy and Nexus coverage analytics for a single metric.
/// </summary>
/// <param name="Metric">Metric identifier.</param>
/// <param name="LegacyValue">Legacy CSV value.</param>
/// <param name="NexusValue">Nexus CSV value.</param>
/// <param name="AbsoluteDifference">Absolute delta between the metrics.</param>
/// <param name="IsWithinTolerance">True when <see cref="AbsoluteDifference"/> is within the configured tolerance.</param>
public sealed record CoverageMetricDifference(
    string Metric,
    double LegacyValue,
    double NexusValue,
    double AbsoluteDifference,
    bool IsWithinTolerance);
